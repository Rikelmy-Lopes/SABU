/// One parsed row of a ballot box bulletin CSV file.
///
/// Field names are the English translation of the official column names.
/// Optional numeric fields are `None` when the file marks them as missing
/// (`#NULO`, `#NE`, `-1`, or `-3`).
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct BulletinRecord {
    pub generation_date: String,
    pub generation_time: String,
    pub election_year: i64,
    pub election_type_code: i64,
    pub election_type_name: String,
    pub plebiscite_code: i64,
    pub plebiscite_date: String,
    pub round: i64,
    pub election_code: i64,
    pub election_description: String,
    pub state_code: String,
    pub municipality_code: i64,
    pub municipality_name: String,
    pub zone: i64,
    pub section: i64,
    pub voting_place: i64,
    pub office_code: i64,
    pub office_name: String,
    pub party_number: i64,
    pub party_acronym: String,
    pub party_name: String,
    pub bulletin_received_at: String,
    pub eligible_voters: Option<i64>,
    pub turnout: Option<i64>,
    pub abstentions: Option<i64>,
    pub ballot_box_type_code: i64,
    pub ballot_box_type_name: String,
    pub votable_type_code: i64,
    pub votable_type_name: String,
    pub votable_number: i64,
    pub votable_name: String,
    pub votes: Option<i64>,
    pub ballot_box_number: Option<i64>,
    pub ballot_box_load_code_prefix: String,
    pub ballot_box_load_code_suffix: String,
    pub flashcard_code: String,
    pub ballot_box_load_date: String,
    pub office_section_label: String,
    pub aggregated_sections: Option<String>,
    pub opened_at: String,
    pub closed_at: String,
    pub biometric_voters_not_enabled: Option<i64>,
    pub bulletin_issued_at: String,
    pub counting_board_number: Option<i64>,
    pub counting_team_number: Option<i64>,
}
